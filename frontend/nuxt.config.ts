/**
 * routeRules are compiled into the server build, so the Laravel address is
 * read from the environment when `nuxt dev` starts or `nuxt build` runs
 * (in production it is a build argument of the frontend image).
 */
const apiBase = process.env.NUXT_API_BASE ?? 'http://app:8000'

const apiProxyRule = { proxy: `${apiBase}/api/**` } as Record<string, unknown>

export default defineNuxtConfig({
  compatibilityDate: '2025-07-15',
  future: { compatibilityVersion: 4 },
  ssr: true,
  devtools: { enabled: false },
  modules: ['@nuxt/ui', '@pinia/nuxt', '@nuxtjs/i18n', '@nuxtjs/sitemap', '@nuxtjs/robots', 'nuxt-schema-org', 'nuxt-seo-utils'],
  app: {
    head: {
      link: [
        { rel: 'icon', href: '/favicon.ico', sizes: '48x48' },
        { rel: 'icon', type: 'image/svg+xml', href: '/favicon.svg', sizes: 'any' },
        { rel: 'apple-touch-icon', href: '/apple-touch-icon.png' },
      ],
    },
  },
  // The public address is the base of canonical links, the sitemap and Open Graph; the
  // environment overrides it (NUXT_PUBLIC_SITE_URL) for staging.
  site: {
    url: 'https://hanyasan.net',
    name: 'PoE Pricer',
    defaultLocale: 'ru',
  },
  i18n: {
    // Russian is the default and has no URL prefix, English lives under /en.
    // The base of the absolute addresses of the language alternatives (hreflang).
    baseUrl: process.env.NUXT_PUBLIC_SITE_URL ?? 'https://hanyasan.net',
    // hreflang and the other language tags of the head are generated by the module itself.
    experimental: { strictSeo: true },
    strategy: 'prefix_except_default',
    defaultLocale: 'ru',
    locales: [
      { code: 'ru', language: 'ru-RU', name: 'Русский', file: 'ru.json' },
      { code: 'en', language: 'en-US', name: 'English', file: 'en.json' },
    ],
    // The language of the browser is applied once, on the first visit of the root; a
    // robot or a visitor that opens an address always gets the language of that address.
    detectBrowserLanguage: {
      useCookie: true,
      cookieKey: 'i18n_redirected',
      redirectOn: 'root',
      fallbackLocale: 'ru',
    },
  },
  robots: {
    disallow: ['/api/', '/_nuxt_icon'],
  },
  schemaOrg: { identity: { type: 'Organization', name: 'PoE Pricer', url: 'https://hanyasan.net', logo: '/logo-mark.svg' } },
  // The dark theme is the default until the visitor picks another one.
  colorMode: { preference: 'dark', fallback: 'dark' },
  css: ['~/assets/css/main.css'],
  // The app uses system fonts only, so the dev server must not wait for the fontshare catalog.
  fonts: { providers: { fontshare: false } },
  icon: {
    // Outside /api, which is proxied to Laravel.
    localApiEndpoint: '/_nuxt_icon',
    // The scanner skips node_modules by default, so point it at the file where
    // Nuxt UI declares its default icons in addition to the app's own sources.
    clientBundle: {
      scan: {
        globInclude: ['app/**/*.vue', 'node_modules/@nuxt/ui/dist/shared/*.mjs'],
        globExclude: ['.nuxt', '.output'],
      },
    },
  },
  nitro: {
    routeRules: {
      '/api/**': apiProxyRule,
    },
  },
  typescript: { strict: true },
})
